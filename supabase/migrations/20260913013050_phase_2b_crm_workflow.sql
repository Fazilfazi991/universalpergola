create or replace function public.submit_public_enquiry(
  p_name text,
  p_phone text,
  p_message text,
  p_whatsapp_number text default null,
  p_email text default null,
  p_emirate text default null,
  p_product_id uuid default null,
  p_honeypot text default null
)
returns table(enquiry_id uuid, enquiry_number bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer_record_id uuid;
  enquiry_record public.enquiries%rowtype;
  phone_key text := private.normalize_phone(p_phone);
  email_key text := private.normalize_email(p_email);
  canonical_product_id uuid;
  recent_count integer;
begin
  if nullif(trim(coalesce(p_honeypot, '')), '') is not null then
    raise exception 'Unable to submit this enquiry';
  end if;
  if char_length(trim(coalesce(p_name, ''))) not between 2 and 160 then
    raise exception 'Enter your name';
  end if;
  if phone_key is null or char_length(phone_key) not between 7 and 15 then
    raise exception 'Enter a valid phone number';
  end if;
  if char_length(trim(coalesce(p_message, ''))) not between 5 and 4000 then
    raise exception 'Tell us briefly what you need';
  end if;
  if email_key is not null and email_key !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    raise exception 'Enter a valid email address';
  end if;

  if p_product_id is not null then
    select p.id into canonical_product_id
    from public.products p
    join public.product_categories c on c.id = p.category_id
    where p.id = p_product_id and p.is_published and p.archived_at is null
      and c.is_active and c.archived_at is null;
    if canonical_product_id is null then
      raise exception 'The selected product is no longer available';
    end if;
  end if;

  select count(*) into recent_count
  from public.enquiries e
  join public.customers c on c.id = e.customer_id
  where c.phone_normalized = phone_key and e.created_at > now() - interval '15 minutes';
  if recent_count >= 5 then
    raise exception 'Please wait before sending another enquiry';
  end if;

  select c.id into customer_record_id
  from public.customers c
  where c.phone_normalized = phone_key and c.archived_at is null
  order by c.updated_at desc
  limit 1;

  if customer_record_id is null then
    insert into public.customers(
      name, phone, whatsapp_number, email, emirate, source, customer_type
    ) values (
      trim(p_name), trim(p_phone), nullif(trim(coalesce(p_whatsapp_number, '')), ''),
      email_key, nullif(trim(coalesce(p_emirate, '')), ''),
      case when canonical_product_id is null then 'Website' else 'Website / Catalogue' end,
      'individual'::public.customer_type
    ) returning id into customer_record_id;
  end if;

  insert into public.enquiries(
    customer_id, product_id, enquiry_type, subject, message, source, priority, status
  ) values (
    customer_record_id, canonical_product_id,
    case when canonical_product_id is null then 'general'::public.enquiry_type else 'catalogue'::public.enquiry_type end,
    case when canonical_product_id is null then 'Website enquiry' else 'Catalogue product enquiry' end,
    trim(p_message), case when canonical_product_id is null then 'Website' else 'Website / Catalogue' end,
    'normal'::public.lead_priority, 'new'::public.enquiry_status
  ) returning * into enquiry_record;

  return query select enquiry_record.id, enquiry_record.enquiry_number;
end;
$$;

create or replace function public.create_staff_enquiry(
  p_customer_id uuid,
  p_customer_name text,
  p_phone text,
  p_whatsapp_number text,
  p_email text,
  p_company_name text,
  p_customer_type public.customer_type,
  p_address text,
  p_area text,
  p_emirate text,
  p_source text,
  p_product_id uuid,
  p_subject text,
  p_message text,
  p_priority public.lead_priority,
  p_assigned_to uuid,
  p_follow_up_at timestamptz,
  p_next_action text,
  p_internal_notes text
)
returns table(enquiry_id uuid, customer_id uuid, enquiry_number bigint)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  customer_record_id uuid := p_customer_id;
  enquiry_record public.enquiries%rowtype;
  actor uuid := (select auth.uid());
begin
  if not private.has_role(array['admin'::public.app_role, 'sales'::public.app_role]) then
    raise exception 'CRM access required';
  end if;
  if customer_record_id is null then
    insert into public.customers(
      name, phone, whatsapp_number, email, company_name, customer_type, address, area,
      emirate, source, assigned_to, created_by
    ) values (
      trim(p_customer_name), nullif(trim(coalesce(p_phone, '')), ''),
      nullif(trim(coalesce(p_whatsapp_number, '')), ''), nullif(trim(coalesce(p_email, '')), ''),
      nullif(trim(coalesce(p_company_name, '')), ''), coalesce(p_customer_type, 'individual'::public.customer_type),
      nullif(trim(coalesce(p_address, '')), ''), nullif(trim(coalesce(p_area, '')), ''),
      nullif(trim(coalesce(p_emirate, '')), ''), nullif(trim(coalesce(p_source, '')), ''),
      case when private.current_user_role() = 'admin'::public.app_role then p_assigned_to else actor end,
      actor
    ) returning id into customer_record_id;
  else
    perform 1 from public.customers c where c.id = customer_record_id and c.archived_at is null;
    if not found then raise exception 'Customer not found'; end if;
  end if;

  insert into public.enquiries(
    customer_id, product_id, enquiry_type, subject, message, source, priority, status,
    assigned_to, follow_up_at, next_action, internal_notes, created_by
  ) values (
    customer_record_id, p_product_id,
    case when p_product_id is null then 'manual'::public.enquiry_type else 'catalogue'::public.enquiry_type end,
    nullif(trim(coalesce(p_subject, '')), ''), nullif(trim(coalesce(p_message, '')), ''),
    nullif(trim(coalesce(p_source, '')), ''), coalesce(p_priority, 'normal'::public.lead_priority),
    'new'::public.enquiry_status,
    case when private.current_user_role() = 'admin'::public.app_role then p_assigned_to else actor end,
    p_follow_up_at, nullif(trim(coalesce(p_next_action, '')), ''),
    nullif(trim(coalesce(p_internal_notes, '')), ''), actor
  ) returning * into enquiry_record;

  return query select enquiry_record.id, customer_record_id, enquiry_record.enquiry_number;
end;
$$;

