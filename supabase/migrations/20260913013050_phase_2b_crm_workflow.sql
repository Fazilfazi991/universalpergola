create or replace function private.protect_crm_management_fields()
returns trigger language plpgsql set search_path = '' as $$
begin
  if private.current_user_role() = 'sales'::public.app_role then
    if new.assigned_to is distinct from old.assigned_to then
      raise exception 'Only management can change salesperson assignments';
    end if;
    if new.archived_at is distinct from old.archived_at then
      raise exception 'Only management can change archive status';
    end if;
  end if;
  return new;
end;
$$;

create trigger customers_protect_management_fields
before update on public.customers
for each row execute function private.protect_crm_management_fields();

create trigger enquiries_protect_management_fields
before update on public.enquiries
for each row execute function private.protect_crm_management_fields();

create or replace function private.protect_follow_up_fields()
returns trigger language plpgsql set search_path = '' as $$
begin
  if old.kind = 'enquiry_follow_up'::public.task_kind
     and private.current_user_role() <> 'admin'::public.app_role
     and (
       new.assigned_to is distinct from old.assigned_to
       or new.enquiry_id is distinct from old.enquiry_id
       or new.customer_id is distinct from old.customer_id
       or new.created_by is distinct from old.created_by
       or new.kind is distinct from old.kind
     ) then
    raise exception 'Only management can reassign or relink follow-ups';
  end if;
  return new;
end;
$$;

create trigger tasks_protect_follow_up_fields
before update on public.tasks
for each row execute function private.protect_follow_up_fields();

create or replace function private.log_customer_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare event_name text;
begin
  if tg_op = 'INSERT' then
    event_name := 'customer.created';
  elsif new.archived_at is not null and old.archived_at is null then
    event_name := 'customer.archived';
  elsif new.archived_at is null and old.archived_at is not null then
    event_name := 'customer.reactivated';
  elsif new.assigned_to is distinct from old.assigned_to then
    event_name := 'customer.salesperson_changed';
  else
    event_name := 'customer.updated';
  end if;
  insert into public.activity_logs(actor_id, event_type, entity_type, entity_id, metadata)
  values ((select auth.uid()), event_name, 'customers', new.id,
    jsonb_strip_nulls(jsonb_build_object('assigned_to', new.assigned_to, 'previous_assigned_to', case when tg_op = 'UPDATE' then old.assigned_to end)));
  return new;
end;
$$;

create or replace function private.log_enquiry_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
    values (new.id, 'enquiry_created', 'Enquiry created', (select auth.uid()));
  else
    if new.assigned_to is distinct from old.assigned_to then
      insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
      values (new.id, 'salesperson_assigned', 'Salesperson assignment changed', (select auth.uid()));
    end if;
    if new.status is distinct from old.status then
      insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
      values (new.id, 'status_changed', 'Status changed from ' || replace(old.status::text, '_', ' ') || ' to ' || replace(new.status::text, '_', ' '), (select auth.uid()));
    end if;
    if new.priority is distinct from old.priority then
      insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
      values (new.id, 'priority_changed', 'Priority changed from ' || old.priority::text || ' to ' || new.priority::text, (select auth.uid()));
    end if;
  end if;
  return new;
end;
$$;

create or replace function private.log_enquiry_activity_entry()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.activity_logs(actor_id, event_type, entity_type, entity_id, metadata)
  values (new.created_by, 'enquiry.' || new.activity_type, 'enquiries', new.enquiry_id,
    jsonb_strip_nulls(jsonb_build_object('activity_id', new.id, 'next_action_at', new.next_action_at)));
  return new;
end;
$$;

create or replace function private.log_follow_up_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.kind <> 'enquiry_follow_up'::public.task_kind or new.enquiry_id is null then
    return new;
  end if;
  if tg_op = 'INSERT' then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, next_action_at, created_by)
    values (new.enquiry_id, 'follow_up_created', new.title, new.due_at, (select auth.uid()));
  elsif new.status = 'completed'::public.task_status and old.status <> 'completed'::public.task_status then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, next_action_at, created_by)
    values (new.enquiry_id, 'follow_up_completed', new.title, new.due_at, (select auth.uid()));
  elsif new.due_at is distinct from old.due_at then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, next_action_at, created_by)
    values (new.enquiry_id, 'follow_up_rescheduled', new.title, new.due_at, (select auth.uid()));
  end if;
  return new;
end;
$$;

