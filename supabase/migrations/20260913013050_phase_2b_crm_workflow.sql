  add constraint enquiries_subject_length check (subject is null or char_length(subject) <= 200),
  add constraint enquiries_message_length check (message is null or char_length(message) <= 6000),
  add constraint enquiries_source_length check (source is null or char_length(source) <= 80),
  add constraint enquiries_next_action_length check (next_action is null or char_length(next_action) <= 300),
  add constraint enquiries_internal_notes_length check (internal_notes is null or char_length(internal_notes) <= 6000);

create or replace function private.normalize_phone(value text)
returns text language sql immutable set search_path = '' as $$
  select nullif(regexp_replace(coalesce(value, ''), '[^0-9]', '', 'g'), '')
$$;

create or replace function private.normalize_email(value text)
returns text language sql immutable set search_path = '' as $$
  select nullif(lower(trim(coalesce(value, ''))), '')
$$;

create or replace function private.normalize_customer_contacts()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.phone := nullif(trim(coalesce(new.phone, '')), '');
  new.whatsapp_number := nullif(trim(coalesce(new.whatsapp_number, '')), '');
  new.email := nullif(lower(trim(coalesce(new.email, ''))), '');
  new.phone_normalized := private.normalize_phone(new.phone);
  new.whatsapp_normalized := private.normalize_phone(new.whatsapp_number);
  new.email_normalized := private.normalize_email(new.email);
  return new;
end;
$$;

