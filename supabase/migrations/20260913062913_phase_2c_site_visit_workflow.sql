create table public.site_visit_measurements (
  id uuid primary key default gen_random_uuid(),
  site_visit_id uuid not null references public.site_visits(id) on delete cascade,
  label text not null,
  width numeric(12,3),
  height numeric(12,3),
  length numeric(12,3),
  unit text not null default 'mm',
  quantity numeric(10,2) not null default 1,
  notes text,
  sort_order integer not null default 0,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint site_visit_measurements_label_length check (char_length(trim(label)) between 2 and 120),
  constraint site_visit_measurements_unit check (unit in ('mm', 'cm', 'm')),
  constraint site_visit_measurements_values check (
    (width is null or width > 0)
    and (height is null or height > 0)
    and (length is null or length > 0)
    and (width is not null or height is not null or length is not null)
  ),
  constraint site_visit_measurements_quantity check (quantity > 0 and quantity <= 1000),
  constraint site_visit_measurements_notes_length check (notes is null or char_length(notes) <= 1000),
  constraint site_visit_measurements_order check (sort_order between -10000 and 10000)
);

