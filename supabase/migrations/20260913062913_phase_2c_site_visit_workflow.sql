create or replace function private.validate_site_visit()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  assignee_valid boolean;
  enquiry_customer uuid;
  role_name public.app_role := private.current_user_role();
  old_status text;
  new_status text := new.status::text;
begin
  if new.assigned_to is not null then
    select exists (
      select 1 from public.profiles p
      where p.id = new.assigned_to and p.status = 'active'::public.profile_status
        and p.role = 'site_team'::public.app_role
    ) into assignee_valid;
    if not assignee_valid then raise exception 'Site visits can only be assigned to active Site Team staff'; end if;
  end if;

  if new.enquiry_id is not null then
    select e.customer_id into enquiry_customer from public.enquiries e where e.id = new.enquiry_id and e.archived_at is null;
    if not found or enquiry_customer is distinct from new.customer_id then
      raise exception 'The visit customer must match the linked enquiry customer';
    end if;
  end if;

  if tg_op = 'INSERT' then
    if role_name = 'sales'::public.app_role and (
      new.created_by is distinct from (select auth.uid())
      or new.assigned_to is not null
      or new.status::text <> 'scheduled'
    ) then raise exception 'Sales can only request unassigned scheduled visits'; end if;
    return new;
  end if;

  if role_name = 'site_team'::public.app_role and (
    new.assigned_to is distinct from old.assigned_to
    or new.customer_id is distinct from old.customer_id
    or new.enquiry_id is distinct from old.enquiry_id
    or new.created_by is distinct from old.created_by
    or new.scheduled_at is distinct from old.scheduled_at
    or new.site_address is distinct from old.site_address
    or new.area is distinct from old.area
    or new.emirate is distinct from old.emirate
    or new.location_url is distinct from old.location_url
    or new.contact_person is distinct from old.contact_person
    or new.contact_phone is distinct from old.contact_phone
    or new.archived_at is distinct from old.archived_at
  ) then raise exception 'Site Team cannot reassign or relink a visit'; end if;

  old_status := old.status::text;
  if new_status is distinct from old_status and not (
    (old_status = 'scheduled' and new_status in ('confirmed', 'rescheduled', 'cancelled', 'no_show'))
    or (old_status = 'confirmed' and new_status in ('in_progress', 'rescheduled', 'cancelled', 'no_show'))
    or (old_status = 'in_progress' and new_status in ('completed', 'cancelled'))
    or (old_status = 'rescheduled' and new_status in ('scheduled', 'confirmed', 'cancelled', 'no_show'))
    or (old_status = 'no_show' and new_status in ('rescheduled', 'cancelled'))
  ) then raise exception 'Invalid site visit status transition from % to %', old_status, new_status; end if;

  if new_status = 'in_progress' and old_status <> 'in_progress' then
    new.actual_started_at := coalesce(new.actual_started_at, now());
  end if;
  if new_status = 'completed' and old_status <> 'completed' then
    if new.assigned_to is null then raise exception 'Assign Site Team staff before completing the visit'; end if;
    if nullif(trim(coalesce(new.notes, '')), '') is null
       and nullif(trim(coalesce(new.measurement_summary, '')), '') is null
       and not exists (select 1 from public.site_visit_measurements m where m.site_visit_id = new.id) then
      raise exception 'Add a visit note, measurement summary, or measurement before completion';
    end if;
    new.completed_at := coalesce(new.completed_at, now());
  end if;
  return new;
end;
$$;

