alter table public.site_visits
  add column visit_number bigint generated by default as identity (start with 2001),
  add column area text,
  add column emirate text,
  add column contact_person text,
  add column contact_phone text,
  add column measurement_summary text,
  add column actual_started_at timestamptz,
  add constraint site_visits_visit_number_key unique (visit_number),
  add constraint site_visits_address_length check (char_length(trim(site_address)) between 2 and 500),
  add constraint site_visits_location_length check (
    (area is null or char_length(area) <= 120)
    and (emirate is null or char_length(emirate) <= 80)
  ),
  add constraint site_visits_contact_length check (
    (contact_person is null or char_length(contact_person) <= 160)
    and (contact_phone is null or char_length(contact_phone) <= 40)
  ),
  add constraint site_visits_maps_url check (
    location_url is null
