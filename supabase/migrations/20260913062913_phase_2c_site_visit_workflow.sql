create or replace function private.validate_crm_assignee()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  assignee_valid boolean;
  expected_customer uuid;
  expected_enquiry uuid;
begin
  if tg_table_name in ('customers', 'enquiries') and new.assigned_to is not null then
    select exists (select 1 from public.profiles p where p.id = new.assigned_to and p.status = 'active'::public.profile_status and p.role = any(array['admin'::public.app_role, 'sales'::public.app_role])) into assignee_valid;
    if not assignee_valid then raise exception 'CRM work can only be assigned to active Management or Sales staff'; end if;
  elsif tg_table_name = 'tasks' and new.assigned_to is not null then
    select exists (
      select 1 from public.profiles p where p.id = new.assigned_to and p.status = 'active'::public.profile_status
      and (
        (new.kind::text = 'enquiry_follow_up' and p.role = any(array['admin'::public.app_role, 'sales'::public.app_role]))
        or (new.kind::text = 'site_visit_follow_up' and p.role = any(array['admin'::public.app_role, 'sales'::public.app_role, 'site_team'::public.app_role]))
        or (new.kind::text = 'general')
      )
    ) into assignee_valid;
    if not assignee_valid then raise exception 'Choose an active staff member permitted for this task'; end if;
  end if;

  if tg_table_name = 'tasks' and new.kind::text = 'enquiry_follow_up' then
    if new.enquiry_id is null then raise exception 'An enquiry follow-up must be linked to an enquiry'; end if;
    select e.customer_id into expected_customer from public.enquiries e where e.id = new.enquiry_id;
    if not found or new.customer_id is distinct from expected_customer then raise exception 'The follow-up customer must match the enquiry customer'; end if;
    if private.current_user_role() = 'sales'::public.app_role and new.assigned_to is distinct from (select auth.uid()) then raise exception 'Sales staff can only assign new follow-ups to themselves'; end if;
  elsif tg_table_name = 'tasks' and new.kind::text = 'site_visit_follow_up' then
    if new.site_visit_id is null then raise exception 'A site follow-up must be linked to a visit'; end if;
    select v.customer_id, v.enquiry_id into expected_customer, expected_enquiry from public.site_visits v where v.id = new.site_visit_id;
    if not found or new.customer_id is distinct from expected_customer or new.enquiry_id is distinct from expected_enquiry then raise exception 'The follow-up links must match the site visit'; end if;
    if private.current_user_role() = 'site_team'::public.app_role and new.assigned_to is distinct from (select auth.uid()) then raise exception 'Site Team can only assign new follow-ups to themselves'; end if;
  end if;
  return new;
end;
$$;

create or replace function private.log_site_visit_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare event_name text;
declare detail text;
begin
  if tg_op = 'INSERT' then
    event_name := 'visit_created'; detail := 'Site visit created';
  elsif new.assigned_to is distinct from old.assigned_to then
    event_name := 'visit_assigned'; detail := 'Site Team assignment changed';
  elsif new.scheduled_at is distinct from old.scheduled_at then
    event_name := 'schedule_changed'; detail := 'Visit schedule changed';
  elsif new.status is distinct from old.status then
    event_name := case new.status::text when 'in_progress' then 'visit_started' when 'completed' then 'visit_completed' when 'cancelled' then 'visit_cancelled' when 'rescheduled' then 'visit_rescheduled' when 'no_show' then 'visit_no_show' else 'status_changed' end;
    detail := 'Status changed from ' || replace(old.status::text, '_', ' ') || ' to ' || replace(new.status::text, '_', ' ');
  else
    event_name := 'visit_updated'; detail := 'Visit details updated';
  end if;
  insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by)
  values (new.id, event_name, detail, (select auth.uid()));
  if new.enquiry_id is not null and tg_op = 'INSERT' then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
    values (new.enquiry_id, 'site_visit_created', detail, (select auth.uid()));
  elsif new.enquiry_id is not null and new.status::text = 'completed' and old.status::text <> 'completed' then
    insert into public.enquiry_activities(enquiry_id, activity_type, note, created_by)
    values (new.enquiry_id, 'site_visit_completed', detail, (select auth.uid()));
  end if;
  return new;
end;
$$;

create or replace function private.log_site_measurement_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare visit_id uuid;
declare measurement_label text;
begin
  if tg_op = 'DELETE' then visit_id := old.site_visit_id; measurement_label := old.label;
  else visit_id := new.site_visit_id; measurement_label := new.label; end if;
  insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by)
  values (visit_id, case tg_op when 'INSERT' then 'measurement_added' when 'UPDATE' then 'measurement_updated' else 'measurement_removed' end, measurement_label, (select auth.uid()));
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create or replace function private.log_site_photo_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare visit_id uuid;
declare photo_note text;
begin
  if tg_op = 'DELETE' then visit_id := old.site_visit_id; photo_note := coalesce(old.caption, old.photo_type, 'Site photo');
  else visit_id := new.site_visit_id; photo_note := coalesce(new.caption, new.photo_type, 'Site photo'); end if;
  insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by)
  values (visit_id, case when tg_op = 'INSERT' then 'photo_uploaded' else 'photo_removed' end, photo_note, (select auth.uid()));
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create or replace function private.log_site_follow_up_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.kind::text <> 'site_visit_follow_up' or new.site_visit_id is null then return new; end if;
  if tg_op = 'INSERT' then
    insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by) values (new.site_visit_id, 'follow_up_created', new.title, (select auth.uid()));
  elsif new.status = 'completed'::public.task_status and old.status <> 'completed'::public.task_status then
    insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by) values (new.site_visit_id, 'follow_up_completed', new.title, (select auth.uid()));
  elsif new.due_at is distinct from old.due_at then
    insert into public.site_visit_activities(site_visit_id, activity_type, note, created_by) values (new.site_visit_id, 'follow_up_rescheduled', new.title, (select auth.uid()));
  end if;
  return new;
end;
$$;

