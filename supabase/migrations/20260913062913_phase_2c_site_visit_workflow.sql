create or replace function private.validate_site_visit_photo()
returns trigger language plpgsql security definer set search_path = '' as $$
declare path_value text := case when tg_op = 'DELETE' then old.storage_path else new.storage_path end;
declare visit_value uuid := case when tg_op = 'DELETE' then old.site_visit_id else new.site_visit_id end;
begin
  if path_value !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|jpeg|png|webp)$'
     or split_part(path_value, '/', 1) <> visit_value::text then
    raise exception 'Invalid site photo path';
  end if;
  if tg_op = 'UPDATE' and (new.site_visit_id is distinct from old.site_visit_id or new.storage_path is distinct from old.storage_path) then
    raise exception 'Site photos cannot be moved between visits';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

