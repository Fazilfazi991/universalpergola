  assigned_to = (select auth.uid()) or created_by = (select auth.uid()) or private.has_role(array['admin'::public.app_role])
  or (enquiry_id is not null and private.can_access_enquiry(enquiry_id))
  or (site_visit_id is not null and private.can_access_site_visit(site_visit_id))
  or (project_id is not null and private.can_access_project(project_id))
);
create policy "staff creates permitted tasks" on public.tasks for insert to authenticated with check (
  private.current_user_role() is not null and created_by = (select auth.uid()) and (
    (kind::text = 'enquiry_follow_up' and enquiry_id is not null and private.has_role(array['admin'::public.app_role, 'sales'::public.app_role]) and private.can_access_enquiry(enquiry_id))
    or (kind::text = 'site_visit_follow_up' and site_visit_id is not null and (private.has_role(array['admin'::public.app_role]) or private.has_role(array['site_team'::public.app_role]) and private.can_access_site_visit(site_visit_id)))
    or (kind::text = 'general' and (enquiry_id is null or private.can_access_enquiry(enquiry_id)) and (site_visit_id is null or private.can_access_site_visit(site_visit_id)))
  )
);
create policy "staff updates permitted tasks" on public.tasks for update to authenticated
using (assigned_to = (select auth.uid()) or created_by = (select auth.uid()) or private.has_role(array['admin'::public.app_role]))
with check (
  (assigned_to = (select auth.uid()) or created_by = (select auth.uid()) or private.has_role(array['admin'::public.app_role]))
  and (enquiry_id is null or private.can_access_enquiry(enquiry_id))
  and (site_visit_id is null or private.can_access_site_visit(site_visit_id))
);

drop policy if exists "visit team views site photos" on storage.objects;
drop policy if exists "visit team uploads site photos" on storage.objects;
drop policy if exists "visit team updates site photos" on storage.objects;
drop policy if exists "visit team deletes site photos" on storage.objects;

create policy "authorized staff views registered site photos" on storage.objects for select to authenticated using (
  bucket_id = 'site-visit-photos' and exists (
    select 1 from public.site_visit_photos p
    where p.storage_path = storage.objects.name and private.can_access_site_visit(p.site_visit_id)
  )
);
create policy "visit operators upload scoped site photos" on storage.objects for insert to authenticated with check (
  bucket_id = 'site-visit-photos'
  and lower(storage.objects.name) ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|jpeg|png|webp)$'
  and exists (
    select 1 from public.site_visits v
    where v.id::text = (storage.foldername(storage.objects.name))[1]
      and (private.has_role(array['admin'::public.app_role]) or (private.has_role(array['site_team'::public.app_role]) and v.assigned_to = (select auth.uid())))
  )
);
create policy "visit operators update registered site photos" on storage.objects for update to authenticated
using (bucket_id = 'site-visit-photos' and owner_id = (select auth.uid()::text) and exists (select 1 from public.site_visit_photos p where p.storage_path = storage.objects.name and private.can_access_site_visit(p.site_visit_id)))
with check (bucket_id = 'site-visit-photos' and owner_id = (select auth.uid()::text) and exists (select 1 from public.site_visit_photos p where p.storage_path = storage.objects.name and private.can_access_site_visit(p.site_visit_id)));
create policy "visit operators delete registered site photos" on storage.objects for delete to authenticated using (
  bucket_id = 'site-visit-photos' and exists (
    select 1 from public.site_visit_photos p where p.storage_path = storage.objects.name
      and (private.has_role(array['admin'::public.app_role]) or (p.created_by = (select auth.uid()) and private.can_access_site_visit(p.site_visit_id)))
  )
);

update storage.buckets set public = false, file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
where id = 'site-visit-photos';

